-- TSM public parcel bounding-box API.
-- Install PostGIS in the dedicated extensions schema; never expose owner PII.
create schema if not exists extensions;
create extension if not exists postgis with schema extensions;

-- SECURITY INVOKER RPCs call qualified PostGIS functions under the caller's role.
-- Schema USAGE exposes function/type names, not table rows or Data API access.
grant usage on schema extensions to anon, authenticated;

create table if not exists public.posey_parcels (
  id bigint generated by default as identity primary key,
  parcel_id text not null,
  source_id text not null,
  source_record_id text,
  source_updated_at timestamptz,
  geom extensions.geometry(MultiPolygon, 4326) not null,
  is_public boolean not null default false,
  verification_status text not null default 'pending'
    check (verification_status in ('pending', 'verified', 'rejected')),
  created_at timestamptz not null default now(),
  constraint posey_parcels_parcel_id_nonempty check (length(btrim(parcel_id)) > 0),
  constraint posey_parcels_source_id_nonempty check (length(btrim(source_id)) > 0),
  constraint posey_parcels_geom_valid check (extensions.st_isvalid(geom)),
  constraint posey_parcels_geom_nonempty check (not extensions.st_isempty(geom))
);

create index if not exists posey_parcels_geom_gix
  on public.posey_parcels using gist (geom);
create index if not exists posey_parcels_public_id_idx
  on public.posey_parcels (id) where is_public;

alter table public.posey_parcels enable row level security;
revoke all on table public.posey_parcels from anon, authenticated;
grant select on table public.posey_parcels to anon, authenticated;

drop policy if exists posey_parcels_public_read on public.posey_parcels;
create policy posey_parcels_public_read
  on public.posey_parcels
  for select
  to anon, authenticated
  using (is_public = true and verification_status = 'verified');

create or replace function public.get_parcels_in_bbox(
  p_xmin double precision,
  p_ymin double precision,
  p_xmax double precision,
  p_ymax double precision
)
returns jsonb
language plpgsql
stable
security invoker
set search_path = ''
as $function$
declare
  result_features jsonb;
  was_truncated boolean;
begin
  if p_xmin is null or p_ymin is null or p_xmax is null or p_ymax is null
     or not (p_xmin between -180 and 180)
     or not (p_xmax between -180 and 180)
     or not (p_ymin between -85.05112878 and 85.05112878)
     or not (p_ymax between -85.05112878 and 85.05112878)
     or p_xmin >= p_xmax or p_ymin >= p_ymax
     or (p_xmax - p_xmin) > 2.0 or (p_ymax - p_ymin) > 2.0 then
    raise exception 'Invalid bounding box; bounds must be ordered and span at most 2 degrees'
      using errcode = '22023';
  end if;

  with candidates as materialized (
    select p.id, p.parcel_id, p.source_id, p.source_record_id,
           p.source_updated_at, p.geom
    from public.posey_parcels as p
    where p.is_public = true
      and p.verification_status = 'verified'
      and p.geom operator(extensions.&&)
          extensions.st_makeenvelope(p_xmin, p_ymin, p_xmax, p_ymax, 4326)
      and extensions.st_intersects(
          p.geom, extensions.st_makeenvelope(p_xmin, p_ymin, p_xmax, p_ymax, 4326)
      )
    order by p.id
    limit 1001
  ),
  page as (
    select * from candidates order by id limit 1000
  )
  select
    coalesce(
      jsonb_agg(
        jsonb_build_object(
          'type', 'Feature',
          'id', page.id,
          'geometry', extensions.st_asgeojson(page.geom)::jsonb,
          'properties', jsonb_build_object(
            'parcel_id', page.parcel_id,
            'source_id', page.source_id,
            'source_record_id', page.source_record_id,
            'source_updated_at', page.source_updated_at
          )
        ) order by page.id
      ),
      '[]'::jsonb
    ),
    (select count(*) > 1000 from candidates)
  into result_features, was_truncated
  from page;

  return jsonb_build_object(
    'type', 'FeatureCollection',
    'features', result_features,
    'truncated', coalesce(was_truncated, false)
  );
end;
$function$;

revoke all on function public.get_parcels_in_bbox(double precision, double precision, double precision, double precision) from public;
grant execute on function public.get_parcels_in_bbox(double precision, double precision, double precision, double precision) to anon, authenticated;

comment on table public.posey_parcels is
  'Public-safe Posey parcel geometry. Only explicitly verified rows may be queried publicly; do not store owner names or other personal data in this table.';
comment on function public.get_parcels_in_bbox(double precision, double precision, double precision, double precision) is
  'Returns at most 1000 public parcel features intersecting a validated WGS84 bounding box; includes truncation metadata.';

notify pgrst, 'reload schema';
