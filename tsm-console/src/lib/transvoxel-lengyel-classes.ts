if (TRANSITION_CELL_CLASS.length !== 512) {
  throw new Error('TRANSITION_CELL_CLASS must have 512 entries');
}

export function getTransitionClass(caseIndex: number): { classId: number; invertWinding: boolean } {
  if (!Number.isInteger(caseIndex) || caseIndex < 0 || caseIndex > 511) {
    throw new RangeError('caseIndex must be 0..511');
  }
  const raw = TRANSITION_CELL_CLASS[caseIndex]!;
  return { classId: raw & 0x7f, invertWinding: (raw & 0x80) !== 0 };
}

export function validateLengyelTables(): { ok: boolean; uniqueClasses: number } {
  const ids = TRANSITION_CELL_CLASS.map((c) => c & 0x7f);
  const unique = new Set(ids);
  const okRange = [...unique].every((c) => c >= 0 && c <= 55);
  const okCount = unique.size === 56;
  return { ok: okRange && okCount, uniqueClasses: unique.size };
}
