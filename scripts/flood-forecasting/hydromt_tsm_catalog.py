#!/usr/bin/env python3
"""
TSM HydroMT Data Catalog for SFINCS Flood Modeling

Builds a HydroMT data catalog YAML pointing at TSM's local data holdings,
then uses the ATphobia22/hydromt fork to generate SFINCS model inputs
for the Ohio/Wabash River confluence.

Upstream: https://github.com/Deltares/hydromt
Fork: https://github.com/ATphobia22/hydromt (local: ~/workspace/forks/hydromt)

Prerequisites:
    conda install hydromt -c conda-forge
    pip install hydromt_sfincs
    # Or use the fork directly:
    pip install ~/workspace/forks/hydromt

Data requirements:
    - DEM: data/posey-county/elevation/in2020-26850945-12-dem-2.5ft.tif
    - BFE: 369.1 ft NAVD88 (FIS 18129CV000A Table 9, Section A)
    - Gages: USGS 03381700 (Ohio at Old Shawneetown), 03378500 (Wabash at New Harmony)

Usage:
    python hydromt_tsm_catalog.py --build-catalog
    python hydromt_tsm_catalog.py --build-sfincs --config sfincs_tristate.yml
"""

import argparse
import sys
from pathlib import Path

# TSM anchor and data paths
TSM_ANCHOR = (37.845887, -88.005075)
TSM_BBOX = (-88.5, 37.5, -87.5, 38.5)  # tristate bounding box

REPO_ROOT = Path(__file__).resolve().parents[2]

DATA_SOURCES = {
    "dem_posey_25ft": {
        "path": "data/posey-county/elevation/in2020-26850945-12-dem-2.5ft.tif",
        "data_type": "RasterDataset",
        "crs": 2968,  # Indiana State Plane West, feet
        "unit": "ft",
        "description": "Posey County 2.5ft DEM, NAVD88",
    },
    "bfe_fis_table9": {
        "path": "data/fabrics/flood-cross-sections/FIS-18129CV000A-Table9-Floodway-Data.csv",
        "data_type": "DataFrame",
        "description": "FIS Table 9, Ohio River floodway data, BFE 369.1 ft NAVD88 at Section A",
    },
    "dnr_cross_sections": {
        "path": "data/fabrics/flood-cross-sections/FLOOD_XS_EFFECTIVE_DNR.csv",
        "data_type": "DataFrame",
        "description": "Indiana DNR effective flood cross-sections, 908 rows",
    },
}


def build_data_catalog(output_path: Path) -> None:
    """Write a HydroMT data catalog YAML for TSM data holdings."""
    lines = [
        "# TSM HydroMT Data Catalog",
        "# Generated by scripts/flood-forecasting/hydromt_tsm_catalog.py",
        "# Root: {}".format(REPO_ROOT),
        "",
        "root: {}".format(REPO_ROOT),
        "",
    ]
    for name, src in DATA_SOURCES.items():
        lines.append(f"{name}:")
        lines.append(f"  path: {src['path']}")
        lines.append(f"  data_type: {src['data_type']}")
        if "crs" in src:
            lines.append(f"  crs: {src['crs']}")
        if "unit" in src:
            lines.append(f"  unit: {src['unit']}")
        lines.append(f"  description: {src['description']}")
        lines.append("")

    output_path.write_text("\n".join(lines))
    print(f"Data catalog written to {output_path}")


def build_sfincs_inputs(config_path: Path) -> None:
    """
    Build SFINCS model inputs using HydroMT.

    This requires hydromt and hydromt_sfincs installed.
    See docs/reference/hydromt-noaa-inundation-integration.md for full setup.
    """
    try:
        import hydromt
    except ImportError:
        print("ERROR: hydromt not installed.", file=sys.stderr)
        print("Install: conda install hydromt -c conda-forge", file=sys.stderr)
        print("   plus: pip install hydromt_sfincs", file=sys.stderr)
        print("Or use the fork: pip install ~/workspace/forks/hydromt", file=sys.stderr)
        sys.exit(1)

    print(f"HydroMT version: {hydromt.__version__}")
    print(f"Building SFINCS inputs from {config_path}...")
    print("")
    print("NOTE: Full SFINCS model build requires:")
    print("  1. hydromt_sfincs plugin installed")
    print("  2. SFINCS binary (deltares/sfincs-cpu Docker)")
    print("  3. Manning's-n landuse map (USDA CDL ingestion — still open)")
    print("  4. Upstream inflow hydrographs (USGS 03381700, 03378500)")
    print("  5. Downstream boundary condition (decision needed)")
    print("")
    print("See docs/reference/hydromt-noaa-inundation-integration.md for the full workflow.")


def main():
    parser = argparse.ArgumentParser(description="TSM HydroMT/SFINCS integration")
    parser.add_argument("--build-catalog", action="store_true",
                        help="Generate HydroMT data catalog YAML")
    parser.add_argument("--build-sfincs", action="store_true",
                        help="Build SFINCS model inputs (requires hydromt)")
    parser.add_argument("--config", type=Path, default=Path("sfincs_tristate.yml"),
                        help="SFINCS build configuration YAML")
    parser.add_argument("--output", type=Path,
                        default=REPO_ROOT / "data/fabrics/hydraulic-models/tsm_data_catalog.yml",
                        help="Output path for data catalog")

    args = parser.parse_args()

    if args.build_catalog:
        build_data_catalog(args.output)
    elif args.build_sfincs:
        build_sfincs_inputs(args.config)
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
